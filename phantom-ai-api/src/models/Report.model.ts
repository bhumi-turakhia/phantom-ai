import { Schema, model, Document, Types } from 'mongoose';

export type ReportStatus = 'generated' | 'archived';

export interface IReportMetadata {
  hasWitnessStatement: boolean;
  hasComposite: boolean;
  hasAuditHistory: boolean;
  imageVerified: boolean;
  imageSha256?: string;
  checkpointSha256?: string;
  pageCount?: number;
}

export interface IReport extends Document {
  _id: Types.ObjectId;
  reportNumber: string;
  case: Types.ObjectId;
  caseNumber: string;
  witnessDescription?: Types.ObjectId;
  composite?: Types.ObjectId;
  compositeVersion?: number;
  title: string;
  generatedBy: Types.ObjectId;
  investigatorName: string;
  investigatorId?: string;
  storageKey: string;
  fileSizeBytes: number;
  sha256: string;
  status: ReportStatus;
  metadata: IReportMetadata;
  notes?: string;
  createdAt: Date;
  updatedAt: Date;
}

const reportSchema = new Schema<IReport>(
  {
    reportNumber: {
      type: String,
      required: [true, 'Report number is required'],
      unique: true,
      trim: true,
      uppercase: true,
      index: true,
    },
    case: {
      type: Schema.Types.ObjectId,
      ref: 'Case',
      required: [true, 'Case reference is required'],
      index: true,
    },
    caseNumber: {
      type: String,
      required: [true, 'Case number is required'],
      trim: true,
      index: true,
    },
    witnessDescription: {
      type: Schema.Types.ObjectId,
      ref: 'WitnessDescription',
    },
    composite: {
      type: Schema.Types.ObjectId,
      ref: 'Composite',
    },
    compositeVersion: {
      type: Number,
    },
    title: {
      type: String,
      required: [true, 'Report title is required'],
      trim: true,
      maxlength: [250, 'Title must not exceed 250 characters'],
    },
    generatedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Generated by is required'],
      index: true,
    },
    investigatorName: {
      type: String,
      required: true,
      trim: true,
    },
    investigatorId: {
      type: String,
      trim: true,
    },
    storageKey: {
      type: String,
      required: [true, 'Storage key is required'],
      trim: true,
    },
    fileSizeBytes: {
      type: Number,
      required: true,
      min: 0,
    },
    sha256: {
      type: String,
      required: [true, 'Report SHA-256 is required'],
      match: [/^[a-f0-9]{64}$/, 'Invalid SHA-256 hash format'],
    },
    status: {
      type: String,
      enum: ['generated', 'archived'],
      default: 'generated',
      index: true,
    },
    metadata: {
      hasWitnessStatement: { type: Boolean, default: false },
      hasComposite: { type: Boolean, default: false },
      hasAuditHistory: { type: Boolean, default: false },
      imageVerified: { type: Boolean, default: false },
      imageSha256: { type: String },
      checkpointSha256: { type: String },
      pageCount: { type: Number, default: 1 },
    },
    notes: {
      type: String,
      trim: true,
      maxlength: [2000, 'Notes must not exceed 2000 characters'],
    },
  },
  {
    timestamps: true,
  }
);

// Compound index for querying reports by case and creation order
reportSchema.index({ case: 1, createdAt: -1 });

export const Report = model<IReport>('Report', reportSchema);

